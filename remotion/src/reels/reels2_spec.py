# --- рилсы-списки: раскладка stack (видео полосой посередине, сверху/снизу коллаж), в начале — картинки Влады с Диска ---
I = lambda n: f"ep2r/img/{n}"          # картинки с Диска (папка «3 вещи / 3 привычки / 3 мифа»)
LB = lambda n: f"ep2/lib/{n}"          # библиотека «Монтажной»
def pic(src, t, x, y, w, h, rot=0, **kw): return dict(src=src, t=t, x=x, y=y, w=w, h=h, rot=rot, **kw)
def slab(text, t, x, y, size=46, rot=-2, **kw): return dict(k="label", text=text, t=t, x=x, y=y - 50, size=size, rot=rot, v=kw.pop("v", "marker"), **kw)
def htext(text, t, y, size, **kw): return dict(k="text", text=text, t=t, y=y, size=size, **kw)
def hook_collage(imgs, he, small, big, color="pink"):
    """коллаж в начале: 3 картинки сверху, 3 снизу, появляются по очереди; поверх — хук цветным шрифтом"""
    T = [(20, 30, 380, 380, -3), (360, 10, 340, 440, 2), (680, 50, 380, 390, -2)]
    B = [(30, 1330, 360, 470, 2), (370, 1360, 360, 450, -3), (700, 1320, 360, 480, 2)]
    items = [pic(src, 0.05 + k * 0.14, *(T + B)[k], **kw) for k, (src, kw) in enumerate(imgs)]
    items += [htext(small, 0.6, 400, 46, font="pf", color="ink", stroke=False, bg="paper"), htext(big, 0.9, 470, 128, color=color, sw=4)]
    return {"kind": "pics", "s": 0, "e": he + 0.25, "items": items}
def body(s, e, l, r, labels=(), extra=()):
    """картинки под видео на время пункта: слева и справа + подписи"""
    return {"kind": "pics", "s": s, "e": e, "items": [pic(l[0], s, 40, 1410, 480, 430, -2, **l[1]), pic(r[0], s + 0.25, 560, 1395, 480, 450, 2, **r[1])] + list(extra) + list(labels)}

